-- ------------------------------------------------------------
-- 공금 예산의 통화
--
-- 지금까지 budgets.amount 는 무조건 원화였고, 잔여 외화는 "원화 잔여 ÷ 현재 환율"로
-- 역산했다. 그런데 실제로는 출발 전에 이미 환전을 해둔다 — NT$9,500 으로 바꿔왔으면
-- 공금은 NT$9,500 이고, 환율이 어떻게 변하든 그 숫자는 고정이어야 한다.
--
-- 예산 항목마다 통화를 달아 "통화별 주머니"로 다룬다. 공금 지출은
--   · 그 통화 주머니가 있으면  -> 그 주머니에서 원금 그대로 차감 (환율 안 씀)
--   · 주머니가 없으면          -> entries.krw 를 원화 주머니에서 차감
-- 두 번째 규칙 덕분에 예산이 전부 원화인 기존 여행은 동작이 그대로다.
-- ------------------------------------------------------------

alter table public.budgets
  add column if not exists currency text not null default 'KRW';

comment on column public.budgets.currency is
  '이 예산 항목을 들고 있는 통화. 이미 환전한 현금이면 그 통화로 고정된다 (환율로 환산하지 않는다).';
comment on column public.budgets.amount is
  'currency 통화로 표시한 금액.';
